"""Generates the pydantic v2 models (python/src/blocwerk_contracts/models) from schemas/ with datamodel-code-generator.

The schemas are copied to a temporary tree with importable names first (runner/hello-response.schema.json ->
runner/hello_response.json, jobs/detect-holds -> jobs/detect_holds). They have no cross-file $refs, so renaming is safe.
Zip layouts (schemas/layouts) describe entry listings, not payloads, and get no models.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = ROOT / "schemas"
OUT = ROOT / "python" / "src" / "blocwerk_contracts" / "models"
SKIPPED = {"layouts"}
HEADER = "# Generated by scripts/generate_python.py from schemas/. Do not edit; run scripts/generate.sh."


def module_path(relative):
    parts = [p.replace("-", "_") for p in relative.parts]
    parts[-1] = parts[-1].removesuffix(".schema.json") + ".json"
    return Path(*parts)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / "schemas"
        for schema in sorted(SCHEMAS.rglob("*.schema.json")):
            relative = schema.relative_to(SCHEMAS)
            if relative.parts[0] in SKIPPED:
                continue
            target = staged / module_path(relative)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(schema, target)
        out = Path(tmp) / "models"
        subprocess.run([
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(staged), "--input-file-type", "jsonschema", "--output", str(out),
            "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.10",
            "--formatters", "builtin", "--disable-timestamp", "--custom-file-header", HEADER,
            "--snake-case-field", "--allow-population-by-field-name",
            "--use-schema-description", "--use-field-description", "--use-standard-collections",
            "--use-union-operator", "--use-annotated", "--collapse-root-models", "--field-constraints", "--enum-field-as-literal", "all",
        ], check=True)
        if OUT.exists():
            shutil.rmtree(OUT)
        shutil.copytree(out, OUT)
    for package in [OUT, *[p for p in OUT.rglob("*") if p.is_dir()]]:
        init = package / "__init__.py"
        if not init.exists() or not init.read_text().strip():
            init.write_text(HEADER + "\n")
    print(f"Generated pydantic models into {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

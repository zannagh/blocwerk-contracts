using System.Text;
using System.Text.RegularExpressions;
using NJsonSchema;
using NJsonSchema.CodeGeneration.CSharp;

namespace GenerateCSharp;

/// <summary>
/// Generates the C# records of <c>Blocwerk.Contracts.Compute</c>: one file per schema, one namespace per schema folder.
/// String enums become plain strings plus a constants class (System.Text.Json cannot round-trip values such as
/// <c>detect-holds</c> through a C# enum), and setters become <c>init</c>.
/// </summary>
public static partial class SchemaToCSharp
{
    private const string RootNamespace = "Blocwerk.Contracts.Compute";

    private const string Header = """
        // Copyright (c) 2026, zannagh. All rights reserved.
        // See License in the project root for license information.
        // Generated by tools/GenerateCSharp from schemas/{0}. Do not edit; run scripts/generate.sh.

        """;

    /// <summary>Folders whose schemas describe zip listings, not payloads: no types for them.</summary>
    private static readonly string[] SkippedFolders = ["layouts"];

    public static async Task<int> RunAsync(string schemasDir, string outputDir)
    {
        if (Directory.Exists(outputDir))
        {
            Directory.Delete(outputDir, recursive: true);
        }

        var files = Directory.GetFiles(schemasDir, "*.schema.json", SearchOption.AllDirectories)
            .Select(f => Path.GetRelativePath(schemasDir, f).Replace('\\', '/'))
            .Where(f => !SkippedFolders.Contains(f.Split('/')[0]))
            .Order(StringComparer.Ordinal)
            .ToList();
        var typesPerNamespace = new Dictionary<string, Dictionary<string, string>>();
        foreach (var relative in files)
        {
            var schema = await LoadAsync(Path.Combine(schemasDir, relative));
            var ns = Namespace(relative);
            var constants = EnumConstants.Strip(schema);
            ShapeRewrites.Apply(schema);
            var (usings, excluded) = CrossFileTypes(schemasDir, Path.Combine(schemasDir, relative));
            var code = Generate(schema, ns, excluded);
            code = code.Replace("#nullable enable\n", "#nullable enable\n" + usings, StringComparison.Ordinal);
            Register(typesPerNamespace, ns, relative, TypeNames(code));
            var target = Path.Combine(outputDir, Path.GetDirectoryName(relative)!, FileStem(relative) + ".g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            await File.WriteAllTextAsync(target, string.Format(Header, relative) + code + EnumConstants.Render(constants, ns, typesPerNamespace[ns], relative));
        }

        Console.WriteLine($"Generated {files.Count} C# files into {outputDir}");
        return 0;
    }

    /// <summary>Loads a schema; NJsonSchema resolves refs between draft-07 <c>definitions</c> only, so 2020-12 <c>$defs</c> are mapped.</summary>
    private static async Task<JsonSchema> LoadAsync(string path)
    {
        var json = (await File.ReadAllTextAsync(path))
            .Replace("\"$defs\":", "\"definitions\":", StringComparison.Ordinal)
            .Replace("#/$defs/", "#/definitions/", StringComparison.Ordinal);
        return await JsonSchema.FromJsonAsync(json, path);
    }

    /// <summary>
    /// A schema that <c>$ref</c>s another file (recognition/detect-request reuses detect-holds/holds-job) reuses that
    /// file's generated types instead of declaring a copy: returns the <c>using</c> lines and the type names to skip.
    /// </summary>
    private static (string Usings, string[] Excluded) CrossFileTypes(string schemasDir, string path)
    {
        var usings = new StringBuilder();
        var excluded = new List<string>();
        var refs = FileReference().Matches(File.ReadAllText(path)).Select(m => m.Groups[1].Value).Distinct();
        foreach (var reference in refs)
        {
            var target = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(path)!, reference));
            using var doc = System.Text.Json.JsonDocument.Parse(File.ReadAllText(target));
            var root = doc.RootElement;
            usings.Append("using ").Append(Namespace(Path.GetRelativePath(schemasDir, target).Replace('\\', '/'))).Append(";\n");
            excluded.Add(root.GetProperty("title").GetString()!);
            if (root.TryGetProperty("$defs", out var defs))
            {
                excluded.AddRange(defs.EnumerateObject().Where(d => d.Value.TryGetProperty("properties", out _)).Select(d => Pascal(d.Name)));
            }
        }

        return (usings.ToString(), excluded.ToArray());
    }

    private static string Generate(JsonSchema schema, string ns, string[] excluded)
    {
        var settings = new CSharpGeneratorSettings
        {
            Namespace = ns,
            JsonLibrary = CSharpJsonLibrary.SystemTextJson,
            ClassStyle = CSharpClassStyle.Poco,
            GenerateNativeRecords = true,
            GenerateNullableReferenceTypes = true,
            GenerateDataAnnotations = false,
            GenerateOptionalPropertiesAsNullable = true,
            GenerateDefaultValues = false,
            ExcludedTypeNames = excluded,
        };
        var code = new CSharpGenerator(schema, settings).GenerateFile();

        // Records are immutable here; the generator only offers set.
        code = code.Replace("{ get; set; }", "{ get; init; }", StringComparison.Ordinal);
        return code.ReplaceLineEndings("\n");
    }

    /// <summary><c>runner/hello.schema.json</c> to <c>Blocwerk.Contracts.Compute.Runner</c>; <c>jobs/detect-holds/…</c> to <c>….Jobs.DetectHolds</c>.</summary>
    internal static string Namespace(string relative)
    {
        var folders = relative.Split('/')[..^1];
        return string.Join('.', new[] { RootNamespace }.Concat(folders.Select(Pascal)));
    }

    /// <summary>Also splits at <c>@</c>, so the capability <c>detect-holds@2</c> becomes the constant <c>DetectHolds2</c>.</summary>
    internal static string Pascal(string name) =>
        string.Concat(name.Split('-', '_', '@').Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

    private static string FileStem(string relative) => Pascal(Path.GetFileName(relative).Replace(".schema.json", string.Empty, StringComparison.Ordinal));

    private static IEnumerable<string> TypeNames(string code) =>
        TypeDeclaration().Matches(code).Select(m => m.Groups[1].Value);

    private static void Register(Dictionary<string, Dictionary<string, string>> all, string ns, string relative, IEnumerable<string> names)
    {
        var known = all.TryGetValue(ns, out var existing) ? existing : all[ns] = [];
        foreach (var name in names)
        {
            if (known.TryGetValue(name, out var other))
            {
                throw new InvalidOperationException($"{ns}.{name} is generated from both {other} and {relative}; rename a $defs entry or a title.");
            }

            known[name] = relative;
        }
    }

    [GeneratedRegex("\"\\$ref\": \"(\\.\\./[^\"#]+\\.schema\\.json)\"")]
    private static partial Regex FileReference();

    [GeneratedRegex(@"public (?:partial )?(?:record|class|enum) (\w+)")]
    private static partial Regex TypeDeclaration();
}
